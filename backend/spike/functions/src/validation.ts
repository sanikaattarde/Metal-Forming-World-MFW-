// SPIKE (DEC-003 OPEN). Small input checks shared by the operations, with no database access.
import { createHash } from 'node:crypto';

export const isObject = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

export const isNonEmptyText = (value: unknown): value is string =>
  typeof value === 'string' && value.trim().length > 0;

// Field names in the input that the operation does not take, for a refusal that names them.
export const unknownFields = (data: Record<string, unknown>, allowed: ReadonlySet<string>): string[] =>
  Object.keys(data).filter((name) => !allowed.has(name));

// The identifier of a new record, generated by the server (INV-14) and derived from the caller's
// request identifier, so that a retry after a lost reply finds the same record and creates no second
// one (API_AND_BACKEND_CONTRACT.md section 2.4). The generator is a spike choice: INV-14 leaves it to
// the implementation.
export const derivedId = (kind: string, uid: string, requestId: string): string =>
  createHash('sha256').update(`${kind}:${uid}:${requestId}`).digest('hex').slice(0, 32);
